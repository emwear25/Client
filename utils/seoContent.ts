/**
 * SEO content for category pages and occasion ("подаръци за …") landing pages.
 *
 * Kept in the storefront (not the DB) so copy is versioned and reviewed with
 * the code. Facts used here (production time, delivery, sizes, name limits)
 * mirror /faq and /shipping - update both together.
 *
 * Paragraph strings may contain simple inline HTML (<a>, <strong>) only.
 */

export interface SeoSection {
  heading: string;
  paragraphs: string[];
  bullets?: string[];
}

export interface SeoFaq {
  q: string;
  a: string;
}

export interface CategorySeo {
  /** <title> without the brand suffix (≤ ~48 chars so "| emWear" fits in 60) */
  title: string;
  /** meta description, 120–160 chars */
  description: string;
  /** visible H1 (falls back to the category displayName) */
  h1?: string;
  /** short intro shown under the H1 */
  intro: string;
  sections: SeoSection[];
  faq: SeoFaq[];
  /** related occasion landing pages for internal linking */
  related?: string[];
}

export interface LandingPage extends CategorySeo {
  slug: string;
  /** short label used in navigation / link lists */
  label: string;
  h1: string;
  /** category slugs whose products are shown, in order */
  categories: string[];
  /** max products shown per category */
  perCategory?: number;
  /** optional hero image (public path) used for og:image */
  image?: string;
}

